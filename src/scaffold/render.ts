import { readFile } from 'node:fs/promises';
import { serializeConfig, validateConfig, type ProjectConfig } from '../config/config.js';

export interface RenderedFile {
  path: string;
  content: string;
}

export const openaiTemplate = {
  framework: 'openai',
  stage: 'runnable',
  files: ['.dockerignore', '.env.example', '.gitignore', 'AGENTS.md', 'README.md', 'Dockerfile',
    'tsconfig.json', 'src/agent.ts', 'src/auth.ts', 'src/config.ts', 'src/main.ts', 'src/server.ts', 'src/tools.ts', 'src/session-store.ts', 'src/redis-session-store.ts',
    'public/index.html', 'public/app.js', 'public/style.css', 'scripts/hash-password.mjs'],
} as const;

// Rendering is separate from destination writes; runtime assets are bundled with the CLI.
export async function renderProject(config: ProjectConfig): Promise<RenderedFile[]> {
  const validated = validateConfig(config);
  const files: RenderedFile[] = await Promise.all(openaiTemplate.files.map(async (path) => {
    // npm excludes literal .gitignore assets from packages, so bundle a named source.
    const source = path === '.gitignore' ? 'gitignore.template' : path;
    return {
      path,
      content: await readFile(new URL(`../../templates/openai/${source}`, import.meta.url), 'utf8'),
    };
  }));
  files.push({ path: 'fastagent.yaml', content: serializeConfig(validated) });
  files.push({
    path: 'package.json',
    content: JSON.stringify({
      name: validated.name,
      version: '0.0.0',
      private: true,
      type: 'module',
      description: 'Protected streaming chat application generated by Fastagent.',
      engines: { node: '>=22' },
      scripts: {
        build: 'tsc',
        typecheck: 'tsc --noEmit',
        start: 'node dist/main.js',
        dev: 'npm run build && node --env-file-if-exists=.env --env-file-if-exists=.env.auth dist/main.js',
        'hash-password': 'node scripts/hash-password.mjs',
      },
      dependencies: { openai: '^6.9.0', yaml: '^2.8.1', zod: '^4.1.8', redis: '^6.3.0' },
      devDependencies: { '@types/node': '^22.0.0', typescript: '^5.9.2' },
    }, null, 2) + '\n',
  });
  return files.sort((a, b) => a.path.localeCompare(b.path, 'en'));
}
